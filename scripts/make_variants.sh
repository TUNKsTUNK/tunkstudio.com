#!/bin/bash
# TUNK: phone-sized copies of the project photographs (macOS, uses sips).
#
# For every JPG/PNG under assets/projects wider than 1500px this writes a
# 1200px-wide JPEG next to it (foo.jpg -> foo.w1200.jpg). The original file is
# never touched; desktops and retina screens still get it. index.html offers
# both through srcset, so a phone downloads the light copy instead.
#
# assets/img-variants.js also records every photo's pixel size, so the page
# can reserve its space before it loads (no layout jumps, and lazy loading
# only fetches what is actually near the screen). Images missing from the
# list (e.g. newly added photos) simply load the original as before.
#
# Run after adding photos:  bash scripts/make_variants.sh
set -euo pipefail
cd "$(dirname "$0")/.."

W=1200
out=assets/img-variants.js
{
  echo "/* generated by scripts/make_variants.sh: src -> [width, height, phone copy or null] */"
  echo "window.IMG_VARIANTS = {"
  find assets/projects -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' \) ! -name "*.w${W}.jpg" | sort |
  while IFS= read -r src; do
    read -r w h < <(sips -g pixelWidth -g pixelHeight "$src" | awk '/pixelWidth/{w=$2} /pixelHeight/{h=$2} END{print w, h}')
    if [ "$w" -gt 1500 ]; then
      dst="${src%.*}.w${W}.jpg"
      if [ ! -f "$dst" ] || [ "$src" -nt "$dst" ]; then
        sips -s format jpeg -s formatOptions 70 --resampleWidth "$W" "$src" --out "$dst" >/dev/null
      fi
      printf '  "%s": [%s, %s, "%s"],\n' "$src" "$w" "$h" "$dst"
    else
      printf '  "%s": [%s, %s, null],\n' "$src" "$w" "$h"
    fi
  done
  echo "};"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "make_variants: $(grep -c '^  "' "$out") images listed, $(grep -c "w${W}.jpg" "$out") with a ${W}px copy"
