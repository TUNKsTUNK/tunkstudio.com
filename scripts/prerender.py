#!/usr/bin/env python3
"""TUNK: static pages for GitHub Pages.

GitHub Pages ignores Netlify's _redirects file, so every path other than
"/" (e.g. /work/postane) used to be answered by 404.html. Visitors saw the
page, but search engines received HTTP 404 and dropped it from the index.

This script writes one real HTML file per route, all built from index.html
(so the React app still boots exactly as before):

  work.html, work/index.html, about.html, press.html, contact.html
  work/<slug>.html                 one per project in data.js
  work/<old-slug>.html             redirect stubs for the 301 lines in _redirects
  sitemap.xml                      regenerated from data.js

Each file gets its own <title>, description, canonical, Open Graph/Twitter
tags and JSON-LD, plus a plain-text copy of the page inside #root, which
React replaces as soon as the app mounts.

Run it after any change to data.js or index.html:  python3 scripts/prerender.py
(The GitHub workflow in .github/workflows/prerender.yml runs it on every push.)
"""
import html
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://tunkstudio.com'
SITE_NAME = 'TUNK'
DEFAULT_IMAGE = SITE + '/assets/logo-tunk-black.png'
GENERATED_MARK = '<!-- generated by scripts/prerender.py: do not edit; edit index.html / data.js -->'


def load_data():
    """Evaluate data.js + seo.js with whatever JS engine is available.

    Returns DATA plus seo.js's own pageSEO() result for every route, so the
    static pages carry exactly the title/description the live app sets.
    """
    src = '\n'.join(open(os.path.join(ROOT, f), encoding='utf-8').read() for f in ('data.js', 'seo.js'))
    expr = ('JSON.stringify({data: DATA, seo: Object.fromEntries('
            '["home","work","about","press","contact"].map(id => [id, pageSEO({id})]).concat('
            'DATA.projects.map(p => ["project:" + p.slug, pageSEO({id: "project", project: p})]))'
            ')})')
    if shutil.which('node'):
        js = 'var window=globalThis;' + src + '\n;process.stdout.write(' + expr + ')'
        out = subprocess.run(['node', '-e', js], capture_output=True, text=True, check=True).stdout
    elif shutil.which('osascript'):  # macOS JavaScriptCore
        js = 'var window=this;' + src + '\n;' + expr
        out = subprocess.run(['osascript', '-l', 'JavaScript', '-e', js],
                             capture_output=True, text=True, check=True).stdout
    else:
        sys.exit('prerender: needs node (or osascript on macOS) to read data.js')
    return json.loads(out)


def esc(s):
    return html.escape(str(s or ''), quote=True)


def abs_url(path):
    return SITE + '/' + path.lstrip('./') if path else DEFAULT_IMAGE


def paragraphs(text):
    return ''.join(f'<p>{esc(p)}</p>' for p in str(text or '').split('\n\n') if p.strip())


def render_head(tpl, title, desc, url, image, og_type, ld, preload=None):
    tpl = re.sub(r'\n[^\n]*data-home-only[^\n]*', '', tpl)  # home-page-only hints (hero preload)
    # index.html computes its <base> in JS (it may be previewed from a nested path), but the
    # browser's preload scanner fetches CSS/JS before that runs, so on /work/x it first asked
    # for /work/app.css etc. (404s, then refetch). Generated pages always live at the site root.
    tpl, n = re.subn(r'<script>\s*/\* The SPA router.*?</script>', '<base href="/" />', tpl, count=1, flags=re.S)
    if not n:
        sys.exit('prerender: <base> script not found in index.html')
    out = re.sub(r'<title>.*?</title>', lambda m: f'<title>{esc(title)}</title>', tpl, count=1, flags=re.S)
    out = re.sub(r'<meta name="description" content="[^"]*"\s*/?>',
                 lambda m: f'<meta name="description" content="{esc(desc)}" />', out, count=1)
    out = re.sub(r'<link rel="canonical" href="[^"]*"\s*/?>',
                 lambda m: f'<link rel="canonical" href="{esc(url)}" />', out, count=1)
    tags = [
        ('property', 'og:type', og_type), ('property', 'og:site_name', SITE_NAME),
        ('property', 'og:title', title), ('property', 'og:description', desc),
        ('property', 'og:url', url), ('property', 'og:image', image),
        ('name', 'twitter:card', 'summary_large_image'), ('name', 'twitter:title', title),
        ('name', 'twitter:description', desc), ('name', 'twitter:image', image),
    ]
    extra = '\n'.join(f'  <meta {a}="{k}" content="{esc(v)}" />' for a, k, v in tags)
    if preload:  # the hero is the largest paint; start it before the app boots
        extra += f'\n  <link rel="preload" as="image" href="{esc(preload)}" fetchpriority="high" />'
    if ld:
        # id matches seo.js, which updates this block on client-side navigation
        extra += ('\n  <script type="application/ld+json" id="ld-page">'
                  + json.dumps(ld, ensure_ascii=False).replace('</', '<\\/') + '</script>')
    return out.replace('</head>', extra + '\n</head>', 1)


def render_page(tpl, body, **head):
    out = render_head(tpl, **head)
    # Visually hidden until React mounts and replaces it; crawlers and
    # no-JS readers get the real text and links.
    root = ('<div id="root"><div class="prerender" style="position:absolute;width:1px;height:1px;'
            'overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap">' + body + '</div></div>')
    out = out.replace('<div id="root"></div>', root, 1)
    return out.replace('<head>', '<head>\n  ' + GENERATED_MARK, 1)


def write(rel, content):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)


def main():
    tpl = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read()
    if GENERATED_MARK in tpl:
        sys.exit('prerender: index.html already contains generated output')
    loaded = load_data()
    data, seo = loaded['data'], loaded['seo']
    projects = data['projects']
    nav = '<nav>' + ' · '.join(f'<a href="/{"" if n["id"] == "home" else n["id"]}">{esc(n["label"])}</a>'
                               for n in data['nav']) + '</nav>'

    # --- section pages
    work_list = '<ul>' + ''.join(
        f'<li><a href="/work/{esc(p["slug"])}">{esc(p["name"])}</a>, '
        f'{esc(p.get("kind") or p.get("category"))}, {esc(p.get("location"))}, {esc(p.get("yearLabel"))}</li>'
        for p in projects) + '</ul>'
    about = data['about']
    about_body = ''.join(paragraphs(v) for k, v in about.items() if re.fullmatch(r'p\d+', k))
    press = data['press']
    press_list = '<ul>' + ''.join(
        f'<li><a href="{esc(i.get("url"))}">{esc(i.get("pub"))}: {esc(i.get("name"))} '
        f'({esc(i.get("year"))})</a></li>' for i in press.get('items', [])) + '</ul>'
    contact = data['contact']
    email = (contact.get('email') or '').lower()

    sections = {
        'work': f'<h1>Work</h1>{work_list}',
        'about': f'<h1>{esc(about.get("heading"))}</h1>{about_body}',
        'press': f'<h1>{esc(press.get("title"))}</h1>{paragraphs(press.get("intro"))}{press_list}',
        'contact': (f'<h1>{esc(contact.get("title"))}</h1><p>{esc(contact.get("address")).replace(chr(10), ", ")}</p>'
                    f'<p><a href="mailto:{esc(email)}">{esc(email)}</a></p>'),
    }
    for sid, body in sections.items():
        s = seo[sid]
        page = render_page(tpl, nav + f'<p>{esc(s["desc"])}</p>' + body, title=s['title'], desc=s['desc'],
                           url=s['url'], image=DEFAULT_IMAGE, og_type='website', ld=None)
        write(f'{sid}.html', page)
        if sid == 'work':  # in case Pages answers /work with the directory instead of work.html
            write('work/index.html', page)

    # --- project pages
    for i, p in enumerate(projects):
        s = seo['project:' + p['slug']]
        loc = p.get('location') or 'Istanbul'
        facts = [('Year', p.get('yearLabel')), ('Location', loc), ('Type', p.get('kind')),
                 ('Category', p.get('category')), ('Status', p.get('status')),
                 ('Scope', ', '.join(p.get('scope') or [])), ('Photography', p.get('photographer')),
                 ('Press', ', '.join(p.get('press') or []))]
        dl = '<dl>' + ''.join(f'<dt>{k}</dt><dd>{esc(v)}</dd>' for k, v in facts if v) + '</dl>'
        # <noscript>: browsers running the app never fetch these twice
        imgs = '<noscript>' + ''.join(
            f'<img src="/{esc(g.lstrip("./"))}" alt="{esc(p["name"])}, {esc(p.get("kind"))}, {esc(loc)}: TUNK Studio" />'
            for g in [p.get('hero')] + [x.get('src') if isinstance(x, dict) else x
                                        for x in p.get('gallery') or []] if g) + '</noscript>'
        nxt = projects[(i + 1) % len(projects)]
        body = (f'{nav}<article><h1>{esc(p["name"])}</h1><p>{esc(s["desc"])}</p>'
                f'{paragraphs(p.get("para"))}{dl}{imgs}</article>'
                f'<p><a href="/work">All projects</a> · Next: <a href="/work/{esc(nxt["slug"])}">{esc(nxt["name"])}</a></p>')
        hero = p.get('hero') if not (p.get('heroVideo') or p.get('heroVideoLocal')) else None
        write(f'work/{p["slug"]}.html',
              render_page(tpl, body, title=s['title'], desc=s['desc'], url=s['url'],
                          image=s.get('image') or DEFAULT_IMAGE, og_type='article', ld=s.get('ld'),
                          preload='/' + hero.lstrip('./') if hero else None))

    # --- old URLs: Pages can't send a 301, so a canonical + instant redirect
    slugs = {p['slug'] for p in projects}
    redirects = 0
    for line in open(os.path.join(ROOT, '_redirects'), encoding='utf-8'):
        m = re.match(r'\s*/work/([^\s/]+)\s+/work/([^\s/]+)\s+30[12]\b', line)
        if m and m.group(1) not in slugs:
            to = f'{SITE}/work/{m.group(2)}'
            write(f'work/{m.group(1)}.html',
                  f'<!DOCTYPE html>\n{GENERATED_MARK}\n<html lang="en"><head><meta charset="UTF-8" />'
                  f'<title>Moved: {SITE_NAME}</title><link rel="canonical" href="{to}" />'
                  f'<meta name="robots" content="noindex" /><meta http-equiv="refresh" content="0; url={to}" />'
                  f'<script>location.replace({json.dumps(to)})</script></head>'
                  f'<body><a href="{to}">{to}</a></body></html>\n')
            redirects += 1

    # --- sitemap
    # project heroes are listed as image entries so they can surface in image search
    urls = [(SITE + '/', None)] + [(f'{SITE}/{s}', None) for s in sections] + \
           [(f'{SITE}/work/{p["slug"]}', p.get('hero')) for p in projects]
    write('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n'
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
          'xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n'
          + ''.join(f'  <url><loc>{u}</loc>'
                    + (f'<image:image><image:loc>{esc(abs_url(img))}</image:loc></image:image>' if img else '')
                    + '</url>\n' for u, img in urls) + '</urlset>\n')

    print(f'prerender: {len(sections)} sections, {len(projects)} projects, '
          f'{redirects} redirects, sitemap {len(urls)} urls')


if __name__ == '__main__':
    main()
